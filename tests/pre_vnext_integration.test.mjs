import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {Engine} from '../src/engine.mjs';
import {authorizeWorkspace,invalidateWorkspaceCache} from '../src/security.mjs';
import {TOOLS,validateArgs} from '../src/tools.mjs';

test('combined release, semantic, browser, risk and native orchestration work without privilege escalation',t=>{
 const base=fs.mkdtempSync(path.join(os.tmpdir(),'a2a-vnext-integration-'));
 let engine=null;
 const env=['HOME','USERPROFILE','APPDATA','A2A_DATA_DIR','VERIFYKIT_DATA_DIR','PLUGIN_DATA'].map(k=>[k,process.env[k]]);
 t.after(()=>{if(engine)engine.close();for(const [k,v] of env)if(v===undefined)delete process.env[k];else process.env[k]=v;invalidateWorkspaceCache();fs.rmSync(base,{recursive:true,force:true})});
 const home=path.join(base,'home'),work=path.join(base,'project');
 fs.mkdirSync(path.join(work,'routes'),{recursive:true});fs.mkdirSync(home);
 fs.mkdirSync(path.join(work,'reports'));
 fs.writeFileSync(path.join(work,'routes','web.php'),"<?php Route::post('/checkout',[PosController::class,'checkout']);");
 fs.writeFileSync(path.join(work,'package.json'),'{"name":"sandbox-fixture"}');
 process.env.HOME=home;process.env.USERPROFILE=home;process.env.APPDATA=path.join(home,'AppData','Roaming');process.env.A2A_DATA_DIR=path.join(base,'plugin-data');
 delete process.env.PLUGIN_DATA;delete process.env.VERIFYKIT_DATA_DIR;
 invalidateWorkspaceCache();authorizeWorkspace(work);
 const e=new Engine();engine=e;
 const plan=e.verify({workspace:work,operation:'plan',changed:['routes/web.php'],criteria:['Unauthorized cashier cannot mutate inventory']});
 assert.equal(plan.state,'not_run');
 assert.ok(plan.risk_guidance.required_test_ids.includes('auth-route-role'));
 assert.ok(plan.risk_guidance.findings.every(f=>f.negative_test_scenarios.every(x=>x.status==='not-run')));
 const advisor=e.context({workspace:work,action:'orchestration',task:{tier:'free',available_commands:['/swarm','@subagent'],workstreams:['auth','data'],dependencies:'low'}});
 assert.equal(advisor.recommended,'@subagent');assert.equal(advisor.automatic_worker_launch,false);
 const ops=TOOLS.find(x=>x.name==='a2a_verify').inputSchema.properties.operation.enum;
 for(const operation of ['assess','assess_release','assess_semantic','assess_browser'])assert.ok(ops.includes(operation));
 validateArgs('a2a_verify',{workspace:work,operation:'assess_browser',artifact:'reports/browser.json'});
 fs.writeFileSync(path.join(work,'reports','release.json'),JSON.stringify({revision:'untrusted',evaluator:{name:'agent',independent:true},scenarios:[{id:'checkout',requirement:'critical',critical:true,verdict:'passed',evidence:[]}],critical_defects:[]}));
 const r=e.verify({workspace:work,operation:'assess_release',artifact:'reports/release.json'});
 assert.equal(r.release_ready,false);assert.equal(r.verdict,'blocked');assert.ok(r.evidence_id);
 fs.writeFileSync(path.join(work,'reports','semantic.json'),JSON.stringify({revision:'untrusted',claims:[{id:'stock',scenario:'true-concurrency',evidence:[{origin:'external-test-harness',revision:'untrusted',verdict:'passed',checked_at:'2026-11-18T09:00:00Z',reference:'ci:run001',witnessed_capabilities:['parallel_clients','shared_stock_record','atomic_commit','one_winner_asserted']}]}]}));
 const sem=e.verify({workspace:work,operation:'assess_semantic',artifact:'reports/semantic.json'});
 assert.equal(sem.release_verified,false);assert.equal(sem.verification_verdict,'inconclusive');
 fs.writeFileSync(path.join(work,'reports','browser.json'),JSON.stringify({schema:'a2a-browser-evidence-v1',scenario_id:'offline-restart',source:{revision:'untrusted'},build:{artifact_sha256:'a'.repeat(64),served_sha256:'a'.repeat(64),source_revision:'untrusted'},environment:{browser:'Chrome',version:'150'},runner:{name:'playwright',version:'1'},started_at:'2026-11-18T09:00:00Z',finished_at:'2026-11-18T09:00:01Z',assertions:[],artifacts:[]}));
 const browser=e.verify({workspace:work,operation:'assess_browser',artifact:'reports/browser.json'});
 assert.equal(browser.independently_verified,false);assert.equal(browser.verification_verdict,'inconclusive');
 const records=e.evidence({workspace:work,operation:'list'});assert.ok(records.items.length>=3);
 assert.ok(records.items.every(x=>x.status!=='passed'));
});
